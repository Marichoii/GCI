"""Package actual v20 evidence; include CSV only after two verified reruns."""
import hashlib
import json
from pathlib import Path
import shutil
import zipfile

from organizar_entregaveis import organize

ROOT=Path(__file__).resolve().parent
DEST=ROOT.parent/"entregaveis/v20"


def copy(source,target):
    target.parent.mkdir(parents=True,exist_ok=True)
    shutil.copy2(source,target)


def package():
    report=json.loads((ROOT/"v20/evidence/experiment_report.json").read_text())
    positive=report["status"]=="gain_confirmed" and report["confirmed"]
    assert positive or report["status"].startswith("rejected_")
    evidence=DEST/"evidence"
    evidence.mkdir(parents=True,exist_ok=True)
    for name in ["v20_search.py","execute_notebook.py","v17_definitions_sha256.json"]:
        copy(ROOT/name,DEST/name)
    copy(ROOT/"v20/gci_home_credit_v20_pesquisa.ipynb",DEST/"gci_home_credit_v20_pesquisa.ipynb")
    for name in ["experiment_report.json","frozen_selection.json"]:
        if (ROOT/"v20/evidence"/name).exists():copy(ROOT/"v20/evidence"/name,evidence/name)
    for name in ["source.ipynb","executed.ipynb","execution_report.json"]:
        copy(ROOT/"v20/runs/pesquisa_02"/name,evidence/"validation"/name)
    copy(ROOT/"v20/pesquisa_02.log",evidence/"validation/console.log")
    repro=None
    if positive:
        repro=json.loads((ROOT/"v20/evidence/reproducibility.json").read_text())
        assert repro["identical_csv_bytes"]
        copy(ROOT/"v20/evidence/reproducibility.json",evidence/"reproducibility.json")
        copy(ROOT/"gci_home_credit_v20.ipynb",DEST/"gci_home_credit_v20.ipynb")
        copy(ROOT/"v20_final_1/runs/reproduction_1/submission.csv",DEST/"output/submission.csv")
        for i in [1,2]:
            directory=ROOT/f"v20_final_{i}/runs/reproduction_{i}"
            for name in ["execution_report.json","executed.ipynb"]:
                copy(directory/name,evidence/f"reproduction_{i}"/name)
            copy(ROOT/f"v20_final_{i}/reproduction_{i}.log",evidence/f"reproduction_{i}/console.log")
        versions=repro["versions"]
    else:
        versions=report["versions"]
        assert not list(DEST.rglob("submission*.csv"))
    (DEST/"requirements.txt").write_text("".join(f"{k}=={v}\n" for k,v in versions.items()))
    # This environment inventory is generated by the same Python as training.
    copy(ROOT/"v20/installed_versions_current.txt",DEST/"installed_versions_local.txt")
    lines=["# Home Credit — resultado v20","",
           "**Ganho confirmado em 2–4 e no total; duas reproduções com CSV idêntico.**" if positive else
           "**Pesquisa sem ganho aprovado; nenhum CSV novo.**","",
           "Somente input/train.csv e input/test.csv. Nenhuma feature de ID; nenhuma previsão, OOF, checkpoint ou modelo salvo carregado. "
           "As 24 definições originais da v17 e o wrapper estrito da MLP foram preservados.","",
           "Quatro candidatos fixados antes dos resultados: LightGBM B com max_bin 255 ou 1023, uma semente 42 cada; "
           "TabM periódico com perda por pares em proporção 50% ou 100%, mesma arquitetura e sementes por parte. "
           "Também se avalia reequilíbrio dos cinco pesos existentes.","",
           "StratifiedKFold(5, shuffle=True, random_state=42), ordem original. "
           "A família é escolhida nas partes 0–1; depois de completar as OOFs, os pesos são fixados usando apenas os rótulos 0–1 e os percentis globais. "
           "O arquivo frozen_selection.json é escrito antes de calcular a AUC do ensemble de confirmação. Não há ajustes após 2–4.","",
           "Busca dos pesos: valores não negativos somando 1; cinco pesos antigos dentro de ±0,10 da v18; "
           "novo componente até 0,30. Inicialização em grade e transferências de massa 0,025/0,01, no máximo quatro rodadas por passo. "
           "Mantém percentis ao quadrado. Nenhum modelo de stacking.","",
           "## Resultado da seleção","",
           f'AUC v18 na triagem, percentis das linhas disponíveis: {report["screening_baseline_auc"]:.8f}.',"",
           "| Estratégia | AUC nas partes 0–1 da triagem |", "|---|---:|"]
    for row in report["screening"]:
        label="Somente reequilíbrio" if row["candidate"] is None else report["configurations"][row["candidate"]]["label"]
        lines.append(f'| {label} | {row["auc"]:.8f} |')
    if "table" in report:
        lines += ["", "## Confirmação com percentis globais", "", "| Parte | v18 | v20 | Diferença |", "|---|---:|---:|---:|"]
        for row in report["table"]:
            lines.append(f'| {row["parte"]} | {row["v18"]:.8f} | {row["v20"]:.8f} | {row["delta"]:+.8f} |')
        lines += ["", f'Componente novo selecionado: `{report["selected_candidate"]}`.',
                  "", "| Componente | Peso | Árvores / épocas no treino integral |", "|---|---:|---:|"]
        labels=["LightGBM B + EXT auxiliares", "LightGBM B — variáveis v7", "MLP — 8 sementes",
                "CatBoost + EXT auxiliares", "TabM periódico original", "TabM periódico — perda por pares"]
        sizes=report["baseline_sizes"]+[report["candidate_size"]]
        for label,weight,size in zip(labels,report["weights"],sizes):
            lines.append(f"| {label} | {weight*100:.6f}% | {size} |")
        lines += ["", "Tamanhos = média do early stopping × 1,15, arredondada. "
                  "Apenas os pesos foram escolhidos com rótulos 0–1; não houve ajuste após a confirmação. "
                  "As partes 0 e 3 tiveram pequenas quedas; os dois agregados exigidos melhoraram.", ""]
    else:
        lines += ["", "Interrompida na triagem: partes 2–4 não executadas; nenhuma nova AUC total.", ""]
    lines += ["## Execução real","",
              f'Pesquisa: {report["total_seconds_including_prepare"]/60:.2f} minutos de tempo decorrido, macOS ARM64 CPU. '
              "A CV usa dois processos independentes com duas threads por modelo; a reprodução final é sequencial com duas threads. "
              "Não foi medido o tempo no Colab.","",
              "Primeira tentativa de inicialização paralela bloqueada pelo sandbox no OpenMP antes de produzir resultados de validação. "
              "A execução registrada em evidence/validation é a pesquisa_02, retomada com acesso à memória compartilhada.",""]
    if positive:
        lines += [f'Execução 1: {repro["seconds"][0]/60:.2f} minutos; execução 2: {repro["seconds"][1]/60:.2f} minutos.',"",
                  "As duas reproduções foram iniciadas em paralelo neste Mac, cada uma em processo novo, "
                  "diretório separado e com duas threads por modelo. Cada reprodução treina seus componentes sequencialmente. "
                  "Todas as células de código foram executadas pelo runner Python incluído, sem kernel Jupyter. "
                  "O tempo e a igualdade de bytes no Colab/Linux não foram verificados.", "",
                  f'CSV SHA-256, execução 1: `{repro["csv_sha256_run_1"]}`.',
                  f'CSV SHA-256, execução 2: `{repro["csv_sha256_run_2"]}`.',"",
                  "O CSV tem 61.500 linhas, IDs na ordem de input/test.csv e colunas SK_ID_CURR,TARGET. "
                  "Score público e rank da v20 permanecem desconhecidos até uma submissão. A melhora local não comprova aumento no placar público.","",
                  "## Como reproduzir o CSV","",
                  "Coloque gci_home_credit_v20.ipynb ao lado de input/train.csv e input/test.csv e execute todas as células em runtime novo. "
                  "A primeira célula instala/verifica versões. O padrão faz o treino integral e grava output/submission.csv. "
                  "Não exige artefatos anteriores nem usa o CSV incluído como entrada.","",
                  "Para refazer a validação, defina GCI_RUN_CV=1 e GCI_CV_ONLY=1 antes da execução; para repetir só o CSV, mantenha os dois em 0.",""]
    else:
        lines += ["Nenhum treino integral de nova candidata ou reprodução de novo CSV foi executado. "
                  "Não há novo SHA-256 de submissão, score público ou rank.","",
                  "Para repetir a pesquisa, coloque o notebook de pesquisa ao lado da pasta input e execute todas as células. "
                  "O runner incluído executa o notebook em processo Python novo; use um nome de execução ainda ausente.",""]
    lines += ["## Versões e fontes","",
              "Versões exatas em requirements.txt e installed_versions_local.txt; Python e plataforma nos relatórios JSON.","",
              "Python 3.11.15. " + "; ".join(f"{name} {version}" for name,version in versions.items()) + ".", "",
              "[LightGBM 4.6 — max_bin](https://lightgbm.readthedocs.io/en/v4.6.0/Parameters.html#max_bin) · "
              "[LibAUC — objetivo por pares](https://docs.libauc.org/api/libauc.losses.html#libauc.losses.PairwiseAUCLoss). "
              "A perda é implementada em PyTorch. Nenhum dado externo ou modelo pré-treinado foi usado.","",
              "A validação usa early stopping e folds já usados em pesquisas anteriores. O ganho é um critério operacional, sem garantia no teste privado.",""]
    (DEST/"RESULTADOS_v20.md").write_text("\n".join(lines))
    rank_path=DEST/"rank.json"
    rank=json.loads(rank_path.read_text())
    rank["observacao"]=("Ganho local confirmado e CSV reproduzido duas vezes; score público e rank aguardam submissão." if positive else
                       "Pesquisa descartada: não houve ganho aprovado; nenhum CSV novo.")
    rank["fonte"]="Validação local; sem resultado público informado"
    rank_path.write_text(json.dumps(rank,ensure_ascii=False,indent=2)+"\n")
    archive=ROOT/"gci_home_credit_v20.zip"
    excluded={"README.md","RANK.md","rank.json","manifesto_sha256.json",archive.name}
    with zipfile.ZipFile(archive,"w",compression=zipfile.ZIP_DEFLATED) as z:
        for file in sorted(DEST.rglob("*")):
            if file.is_file() and file.name not in excluded:z.write(file,str(file.relative_to(DEST)))
    with zipfile.ZipFile(archive) as z:assert z.testzip() is None
    organize("v20")
    print(archive,archive.stat().st_size,hashlib.sha256(archive.read_bytes()).hexdigest())


if __name__=="__main__":package()
